/**
 * The core's named constants, in Swift, made from the TypeScript.
 *
 *   npm run swift:constants            write them from src/core/ (npm test does)
 *   npm run swift:constants -- --check write them, and fail if that changed them
 *
 * Every number the two cores must share is written once, in src/core/, and
 * this writes the Swift twin's copy of it, committed, since neither Xcode nor
 * SwiftPM runs node: EggTimerCore/Constants.generated.swift and, for the
 * formatter's two, EggTimerCopy/Constants.generated.swift. Each value is read
 * from the module's export, so a derived constant (480 / ln 1.5) is the
 * TypeScript's double, and is printed as JavaScript prints it, the shortest
 * decimal that reads back to the same double, which Swift's literal does
 * (the twins need agree only to 1e-12, but a literal costs nothing). Each keeps
 * the first sentence of its doc comment; the rest of its provenance is the
 * TypeScript's.
 *
 * Every SCREAMING_CASE `const` in src/core/ is either twinned below or listed
 * in NOT_TWINNED with the reason, so a constant added to the TypeScript
 * fails this until it is one or the other; a twinned one must be exported.
 *
 * `npm test` runs this before it type-checks, as it does copy:keys, so the
 * Swift's constants are never a step to remember. `--check` is
 * `fixtures:check`'s rule for generated files, as in tools/copyKeys.ts: what
 * is written must be what was there. It compares with the working tree, not
 * the commit, so it fails a constant committed without its twin only where
 * nothing has rewritten the twin first: CI runs it on the clean checkout
 * before npm test, and ends with `git diff --exit-code`. Locally, after an
 * npm test, the twin on disk is fresh whether or not it was committed, so
 * `npm run verify` also fails a generated file with uncommitted changes.
 */


/** `customMinor_mm` -> `customMinorMm`: a field as a Swift name. */
function camel(field: string): string {
  return field.split('_').map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join('');
}

/** A double as Swift reads it back: JavaScript's shortest round trip. */
function double(x: unknown, what: string): string {
  if (typeof x !== 'number' || !Number.isFinite(x)) throw new Error(`${what}: ${String(x)} is not a finite number`);
  const s = String(x);
  return /[.eE]/.test(s) ? s : `${s}.0`;
}

function int(x: unknown, what: string): string {
  if (!Number.isInteger(x)) throw new Error(`${what}: ${String(x)} is not an integer`);
  return String(x);
}

/** A string as a Swift literal: ASCII printable as it is, the rest escaped. */
function string(x: unknown, what: string): string {
  if (typeof x !== 'string') throw new Error(`${what}: not a string`);
  let out = '';
  for (const ch of x) {
    const c = ch.codePointAt(0) as number;
    if (ch === '"' || ch === '\\') out += `\\${ch}`;
    else if (c >= 0x20 && c < 0x7f) out += ch;
    else out += `\\u{${c.toString(16).toUpperCase()}}`;
  }
  return `"${out}"`;
}

/** An object's field. */
function field(o: unknown, key: string, what: string): unknown {
  if (o === null || typeof o !== 'object' || !(key in o)) throw new Error(`${what}: no ${key}`);
  return (o as Record<string, unknown>)[key];
}

function literal(value: unknown, type: SwiftType, what: string): string {
  const f = (o: unknown, k: string) => field(o, k, what);
  const rows = (fn: (o: unknown) => string) => {
    if (!Array.isArray(value)) throw new Error(`${what}: not a list`);
    return `[\n${value.map((o) => `    ${fn(o)},`).join('\n')}\n]`;
  };
  switch (type) {
    case 'Double': return double(value, what);
    case 'Int': case 'Int32': return int(value, what);
    case 'String': case 'Unicode.Scalar': return string(value, what);
    case '[Double]': return rows((x) => double(x, what));
    case 'ClosedRange<Double>': return `${double(f(value, 'lo'), what)}...${double(f(value, 'hi'), what)}`;
    case '[SizeClass]':
      return rows((o) => `SizeClass(key: .\`${String(f(o, 'key'))}\`, massKg: ${double(f(o, 'mass_kg'), what)})`);
    case '[DonenessAnchor]':
      return rows((o) => `DonenessAnchor(key: .\`${String(f(o, 'key'))}\`, level: ${double(f(o, 'level'), what)},`
        + ` approxPeakYolkC: ${double(f(o, 'approxPeakYolk_C'), what)})`);
    case 'Population': {
      const logNormal = (k: string) => `LogNormal(median: ${double(f(f(value, k), 'median'), what)}, logSd: ${double(f(f(value, k), 'logSd'), what)})`;
      const normal = (k: string) => `Normal(mean: ${double(f(f(value, k), 'mean'), what)}, sd: ${double(f(f(value, k), 'sd'), what)})`;
      return `Population(\n    id: ${string(f(value, 'id'), what)},\n    alphaM2s: ${logNormal('alpha_m2s')},\n`
        + `    logDoseOffset: ${normal('logDoseOffset')},\n    noise: ${logNormal('noise')},\n`
        + `    whiteOffset: ${normal('whiteOffset')},\n    whiteFirmGap: ${logNormal('whiteFirmGap')}\n)`;
    }
  }
}

const sources = new Map<string, string>();
function source(module: string): string {
  let text = sources.get(module);
  if (text === undefined) {
    text = readFileSync(`src/core/${module}`, 'utf8');
    sources.set(module, text);
  }
  return text;
}

/** The comment that ends where `text` does: a doc comment, or `//` lines;
 *  none for a plain block comment, or none at all. */
function commentAbove(text: string): string[] {
  const lines = text.replace(/\s+$/, '').split('\n');
  const slashes: string[] = [];
  while (lines.length > 0 && lines[lines.length - 1].trim().startsWith('//')) {
    slashes.unshift((lines.pop() as string).trim().replace(/^\/\/ ?/, ''));
  }
  if (slashes.length > 0) return slashes;
  const before = lines.join('\n');
  if (!before.endsWith('*/')) return [];
  const open = before.lastIndexOf('/*');
  if (before.slice(open, open + 3) !== '/**') return [];
  return before.slice(open + 3, -2).split('\n').map((l) => l.replace(/^\s*\* ?/, '').trim()).filter((l) => l !== '');
}

/** The comment just above `const name`. */
function docOf(module: string, name: string): string[] {
  const text = source(module);
  const at = new RegExp(`^(?:export )?const ${name}\\b`, 'm').exec(text);
  if (at === null) throw new Error(`src/core/${module} declares no ${name}`);
  return commentAbove(text.slice(0, at.index));
}

/** The comment just above `key:` in the object `const name` declares. */
function fieldDocOf(module: string, name: string, key: string): string[] {
  const text = source(module);
  const at = new RegExp(`^(?:export )?const ${name}\\b`, 'm').exec(text);
  if (at === null) throw new Error(`src/core/${module} declares no ${name}`);
  const body = text.slice(at.index);
  const f = new RegExp(`^[ \\t]*${key}:`, 'm').exec(body);
  return f === null ? [] : commentAbove(body.slice(0, f.index));
}

/** A comment's first sentence, as a Swift doc comment wrapped to 100
 *  columns: what the constant is. Why it is that is the TypeScript's. */
function doc(lines: string[], indent: string): string {
  const text = lines.join(' ').replace(/\s+/g, ' ').trim();
  const end = /[.!?](?=\s+[^\sa-z]|$)/.exec(text.replace(/\b(e\.g|i\.e|et al)\./g, (m) => m.replace(/\./g, '\u0000')));
  const sentence = end === null ? text : text.slice(0, end.index + 1);
  const out: string[] = [];
  let line = '';
  for (const word of sentence.split(' ')) {
    if (line !== '' && `${indent}/// ${line} ${word}`.length > 100) {
      out.push(line);
      line = word;
    } else {
      line = line === '' ? word : `${line} ${word}`;
    }
  }
  if (line !== '') out.push(line);
  return out.map((l) => `${indent}/// ${l}`).join('\n');
}

/** Every SCREAMING_CASE const each core module declares, and whether exported. */
function declared(): { module: string; name: string; exported: boolean }[] {
  const out: { module: string; name: string; exported: boolean }[] = [];
  for (const module of readdirSync('src/core').filter((f) => f.endsWith('.ts')).sort()) {
    for (const m of source(module).matchAll(/^(export )?const ([A-Z][A-Z0-9_]*)\b/gm)) {
      out.push({ module, name: m[2], exported: m[1] !== undefined });
    }
  }
  return out;
}

/** A namespace's doc, as written. */
function namespaceDoc(ns: string): string {
  const from = NAMESPACES[ns];
  if (from === undefined) throw new Error(`${ns} is no namespace in NAMESPACES`);
  return doc(typeof from === 'string' ? [from] : docOf(from[0], from[1]), '');
}

async function swiftFiles(): Promise<[string, string][]> {
  const problems: string[] = [];
  const twinned = new Set(TWINS.map((t) => `${t.module} ${t.name.split('.')[0]}`));
  for (const d of declared()) {
    const id = `${d.module} ${d.name}`;
    if (twinned.has(id)) {
      if (!d.exported) problems.push(`src/core/${d.module}: ${d.name} is twinned, and not exported`);
    } else if (!(id in NOT_TWINNED)) {
      problems.push(`src/core/${d.module}: ${d.name} is neither twinned nor in NOT_TWINNED (tools/swiftConstants.ts)`);
    }
  }
  for (const id of Object.keys(NOT_TWINNED)) {
    const [module, name] = id.split(' ');
    if (!declared().some((d) => d.module === module && d.name === name)) problems.push(`NOT_TWINNED names ${id}, which is gone`);
  }
  if (problems.length > 0) throw new Error(problems.join('\n'));

  const modules = new Map<string, Record<string, unknown>>();
  for (const module of new Set(TWINS.map((t) => t.module))) {
    modules.set(module, await import(`../src/core/${module}`) as Record<string, unknown>);
  }

  const files: [string, string][] = [];
  for (const [target, path] of [[undefined, CORE_SWIFT], ['copy', COPY_SWIFT]] as const) {
    const twins = TWINS.filter((t) => t.target === target);
    const top: string[] = [];
    const members = new Map<string, string[]>();
    let lastModule = '';
    for (const t of twins) {
      const [root, ...path] = t.name.split('.');
      let value: unknown = (modules.get(t.module) as Record<string, unknown>)[root];
      for (const k of path) value = field(value, k, t.name);
      const type = t.type ?? 'Double';
      const dot = t.swift.indexOf('.');
      const namespace = dot < 0 ? null : t.swift.slice(0, dot);
      const name = dot < 0 ? t.swift : t.swift.slice(dot + 1);
      const indent = namespace === null ? '' : '    ';
      const access = t.internal ? '' : 'public ';
      const lines = path.length === 0 ? docOf(t.module, root) : fieldDocOf(t.module, root, path[path.length - 1]);
      const decl = `${indent}${access}${namespace === null ? '' : 'static '}let ${name}: ${type} = `
        + literal(value, type, t.name).split('\n').join(`\n${indent}`);
      const said = lines.length > 0 && (namespace === null || doc(lines, '') !== namespaceDoc(namespace));
      const text = `${said ? `${doc(lines, indent)}\n` : ''}${decl}`;
      if (namespace === null) {
        if (t.module !== lastModule) top.push(`// MARK: - src/core/${t.module}`);
        lastModule = t.module;
        top.push(text);
      } else {
        members.set(namespace, [...(members.get(namespace) ?? []), text]);
      }
    }
    const spaces = [...members.entries()].map(([ns, decls]) => {
      return `${namespaceDoc(ns)}\npublic enum ${ns} {\n${decls.join('\n')}\n}`;
    });
    const body = [...spaces, ...top].join('\n\n');
    files.push([path, `// ${HEADER}\n\n${body}\n`]);
  }
  return files;
}


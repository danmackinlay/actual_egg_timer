/**
 * The catalogue's keys, as types both compilers check (DECISIONS.md 127).
 *
 *   npm run copy:keys            write them from copy/en.json
 *   npm run copy:keys -- --check write them, and fail unless git has them
 *
 * From copy/en.json, two files, committed, since neither Xcode nor SwiftPM
 * runs node:
 *
 * - src/core/copyKeys.ts: `CopyKeyArgs`, each key and the names of the
 *   arguments it is rendered with, and `CopyKey`, the union of the keys. The
 *   web's `t()` takes a `CopyKey` and exactly its arguments, so a key that is
 *   not in the catalogue, or a missing or extra argument, fails `tsc`.
 * - EggTimerCopy/CopyKeys.swift: `enum CopyKey: String`, one case per key,
 *   each spelled as the key is (a raw identifier, `` .`app.name` ``), so a
 *   key the catalogue lacks fails `swift build`; and each key's argument
 *   names, which `tr()` checks in a debug build.
 *
 * A key's arguments are the placeholders of every template it has, and the
 * plural count, which a template need not show.
 *
 * `--check` is `fixtures:check`'s rule for generated files: what is written
 * must be what git's index has, so a catalogue changed without its keys
 * fails verify and CI.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

import { parseCatalogue, placeholders, templatesOf } from '../src/core/copy.js';
import { replaceFile } from './fixtureCompare.js';

export const TS_KEYS = 'src/core/copyKeys.ts';
export const SWIFT_KEYS = 'ios/EggTimerCore/Sources/EggTimerCopy/CopyKeys.swift';

const HEADER = 'Generated by tools/copyKeys.ts from copy/en.json (npm run copy:keys): do not hand-edit.';

/** Each key of the catalogue, in its order, with its arguments' names. */
function keysOf(path: string): [string, string[]][] {
  const en = parseCatalogue(JSON.parse(readFileSync(path, 'utf8')));
  return [...en.messages.entries()].map(([key, m]) => {
    const names = new Set(templatesOf(m).flatMap(placeholders));
    if (m.kind === 'plural') names.add(m.count);
    return [key, [...names].sort()];
  });
}

function typescript(keys: [string, string[]][]): string {
  const rows = keys.map(([key, names]) => `  '${key}': ${names.length === 0 ? 'never' : names.map((n) => `'${n}'`).join(' | ')};`);
  return `// ${HEADER}

/** Every key of the catalogue, and the names of the arguments it is rendered
 *  with; \`never\` for a key that takes none. */
export interface CopyKeyArgs {
${rows.join('\n')}
}

/** A key of the catalogue. */
export type CopyKey = keyof CopyKeyArgs;
`;
}

function swift(keys: [string, string[]][]): string {
  const cases = keys.map(([key]) => `    case \`${key}\` = "${key}"`);
  const named = keys.filter(([, names]) => names.length > 0)
    .map(([key, names]) => `        .\`${key}\`: [${names.map((n) => `"${n}"`).join(', ')}],`);
  return `// ${HEADER}

/// A key of the catalogue, spelled as the catalogue spells it.
public enum CopyKey: String, Sendable, CaseIterable {
${cases.join('\n')}

    /// The names of the arguments the key is rendered with: none, for a key
    /// not listed.
    public static let argumentNames: [CopyKey: Set<String>] = [
${named.join('\n')}
    ]
}
`;
}

const keys = keysOf('copy/en.json');
const written: [string, string][] = [[TS_KEYS, typescript(keys)], [SWIFT_KEYS, swift(keys)]];
for (const [path, text] of written) replaceFile(path, text);

if (process.argv.includes('--check')) {
  const stale: string[] = [];
  for (const [path, text] of written) {
    let committed: string | null = null;
    try {
      committed = execFileSync('git', ['show', `:${path}`], { encoding: 'utf8', maxBuffer: 1 << 26 });
    } catch {
      committed = null;
    }
    if (committed !== text) stale.push(path);
  }
  if (stale.length > 0) {
    console.error(`copy:keys: ${stale.join(' and ')} not as copy/en.json makes them; written, to be committed (\`git diff\`)`);
    process.exit(1);
  }
  console.log(`copy:keys: the ${keys.length} keys agree with copy/en.json`);
} else {
  console.log(`copy:keys: ${keys.length} keys written to ${TS_KEYS} and ${SWIFT_KEYS}`);
}
